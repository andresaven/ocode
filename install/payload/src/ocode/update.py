from __future__ import annotations

import json
import re
import shutil
import tempfile
import urllib.error
import urllib.request
import zipfile
from dataclasses import dataclass
from pathlib import Path

GITHUB_REPO = "andresaven/ocode"
LATEST_RELEASE_URL = f"https://api.github.com/repos/{GITHUB_REPO}/releases/latest"
TAGS_URL = f"https://api.github.com/repos/{GITHUB_REPO}/tags"
ARCHIVE_URL = f"https://github.com/{GITHUB_REPO}/archive/refs/tags/{{tag}}.zip"
USER_AGENT = "ocode-updater"
TIMEOUT_SECONDS = 15

_VERSION_RE = re.compile(r"^[vV]?(\d+(?:\.\d+)*)")
_PACKAGE_VERSION_RE = re.compile(
    r"^__version__\s*=\s*['\"]([^'\"]+)['\"]\s*$",
    re.MULTILINE,
)


class UpdateError(RuntimeError):
    """Fallo al consultar, descargar o preparar una actualización."""


@dataclass(frozen=True)
class Release:
    tag: str
    version: str
    name: str = ""
    notes: str = ""
    url: str = ""

    @property
    def archive_url(self) -> str:
        """Source-code ZIP generated by GitHub for the release tag."""
        return ARCHIVE_URL.format(tag=self.tag)


def parse_version(text: str) -> tuple[int, ...] | None:
    """Return the numeric version of a tag, or None if it has no version."""
    match = _VERSION_RE.match(text.strip())
    if match is None:
        return None
    parts = [int(part) for part in match.group(1).split(".")]
    # Pad so that 0.6 and 0.6.0 compare as equal.
    while len(parts) < 3:
        parts.append(0)
    return tuple(parts)


def format_version(version: tuple[int, ...]) -> str:
    return ".".join(str(part) for part in version)


def is_newer(candidate: str, current: str) -> bool:
    new = parse_version(candidate)
    installed = parse_version(current)
    if new is None or installed is None:
        return False
    return new > installed


def is_prerelease(tag: str) -> bool:
    """A stable tag only contains digits and dots after an optional 'v'."""
    stripped = tag.strip()
    if stripped[:1] in ("v", "V"):
        stripped = stripped[1:]
    return bool(stripped) and re.search(r"[^0-9.]", stripped) is not None


def _request_json(url: str) -> tuple[int, object]:
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": USER_AGENT,
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            payload = response.read().decode("utf-8")
    except urllib.error.HTTPError as exc:
        return exc.code, None
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise UpdateError(f"No se pudo consultar GitHub: {exc}") from exc

    try:
        return 200, json.loads(payload)
    except ValueError as exc:
        raise UpdateError("GitHub devolvió una respuesta no válida.") from exc


def _latest_tag() -> Release | None:
    """Fallback used while a tag exists but no GitHub release is published."""
    status, data = _request_json(TAGS_URL)
    if status != 200 or not isinstance(data, list):
        return None

    best: Release | None = None
    best_version: tuple[int, ...] | None = None
    for item in data:
        if not isinstance(item, dict):
            continue
        tag = str(item.get("name") or "").strip()
        if not tag or is_prerelease(tag):
            continue
        version = parse_version(tag)
        if version is None:
            continue
        if best_version is None or version > best_version:
            best_version = version
            best = Release(tag=tag, version=format_version(version))
    return best


def latest_release() -> Release | None:
    """Latest stable release, or the highest stable tag as a fallback."""
    status, data = _request_json(LATEST_RELEASE_URL)
    if status == 200 and isinstance(data, dict):
        tag = str(data.get("tag_name") or "").strip()
        version = parse_version(tag)
        if version is not None and not is_prerelease(tag):
            return Release(
                tag=tag,
                version=format_version(version),
                name=str(data.get("name") or tag),
                notes=str(data.get("body") or "").strip(),
                url=str(data.get("html_url") or ""),
            )
    return _latest_tag()


def check_for_update(current: str) -> Release | None:
    """Return the new release to install, or None when already up to date."""
    release = latest_release()
    if release is None:
        return None
    if is_newer(release.version, current):
        return release
    return None


def launcher_for(home: Path) -> Path:
    """Prefer the host updater; fall back to the staged installer."""
    update_launcher = home / "update.cmd"
    if update_launcher.is_file():
        return update_launcher
    return home / "install" / "install.cmd"


def _download(release: Release, destination: Path) -> Path:
    request = urllib.request.Request(
        release.archive_url,
        headers={"User-Agent": USER_AGENT},
    )
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            with destination.open("wb") as handle:
                shutil.copyfileobj(response, handle)
    except urllib.error.HTTPError as exc:
        raise UpdateError(
            f"El paquete de ocode {release.version} no está disponible (HTTP {exc.code})."
        ) from exc
    except (urllib.error.URLError, TimeoutError, OSError) as exc:
        raise UpdateError(
            f"No se pudo descargar ocode {release.version}: {exc}"
        ) from exc
    return destination


def _extract(archive: Path, target: Path) -> None:
    target_root = target.resolve()
    try:
        with zipfile.ZipFile(archive) as bundle:
            for member in bundle.infolist():
                member_path = Path(member.filename)
                if member_path.is_absolute() or ".." in member_path.parts:
                    raise UpdateError("El paquete descargado contiene rutas no seguras.")
                resolved = (target_root / member.filename).resolve()
                if resolved != target_root and target_root not in resolved.parents:
                    raise UpdateError(
                        "El paquete descargado intenta salir del directorio de destino."
                    )
            bundle.extractall(target_root)
    except zipfile.BadZipFile as exc:
        raise UpdateError("El paquete descargado no es un ZIP válido.") from exc


def _distribution_root(extracted: Path) -> Path:
    """GitHub wraps the source ZIP in a single top-level folder."""
    entries = sorted(extracted.iterdir())
    if len(entries) == 1 and entries[0].is_dir():
        return entries[0]
    return extracted


def _validate_distribution(root: Path, expected_version: str) -> None:
    required = (
        root / "install" / "install.cmd",
        root / "install" / "install.py",
        root / "install" / "payload" / "pyproject.toml",
        root / "install" / "payload" / "src" / "ocode" / "__main__.py",
        root / "install" / "payload" / "src" / "ocode" / "__init__.py",
    )
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise UpdateError(
            "El paquete descargado no contiene la distribución esperada:\n"
            + "\n".join(missing)
        )

    version_path = root / "install" / "payload" / "src" / "ocode" / "__init__.py"
    match = _PACKAGE_VERSION_RE.search(version_path.read_text(encoding="utf-8"))
    if match is None or match.group(1) != expected_version:
        included = match.group(1) if match is not None else "desconocida"
        raise UpdateError(
            f"La actualización anuncia ocode {expected_version}, pero el paquete "
            f"incluye ocode {included}. No se ha instalado."
        )


def _replace_install(source: Path, target: Path) -> None:
    """Swap the installer tree, restoring the previous one if copying fails."""
    target.parent.mkdir(parents=True, exist_ok=True)
    backup = target.with_name(target.name + ".ocode-backup")
    if backup.is_dir():
        shutil.rmtree(backup)
    if target.exists():
        target.rename(backup)
    try:
        shutil.copytree(source, target)
    except BaseException:
        shutil.rmtree(target, ignore_errors=True)
        if backup.exists():
            backup.rename(target)
        raise
    if backup.exists():
        shutil.rmtree(backup, ignore_errors=True)


def stage_update(release: Release, home: Path) -> Path:
    """Download and stage a release inside OCODE_HOME.

    Replaces ``install/`` with the new distribution and leaves the actual
    installation to the host installer. Returns the launcher to run.
    """
    home = Path(home)
    with tempfile.TemporaryDirectory(prefix="ocode-update-") as temp_dir:
        workspace = Path(temp_dir)
        archive = _download(release, workspace / f"ocode-{release.version}.zip")
        extracted = workspace / "extracted"
        extracted.mkdir()
        _extract(archive, extracted)
        root = _distribution_root(extracted)
        _validate_distribution(root, release.version)
        _replace_install(root / "install", home / "install")
        readme = root / "README.md"
        if readme.is_file():
            shutil.copy2(readme, home / "README.md")
    return launcher_for(home)
